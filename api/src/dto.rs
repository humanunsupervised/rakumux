/// Server → client text messages on `GET /v1/events` (WebSocket).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum EventMessage {
    /// Sent once, first: the subscription is live.
    Subscribed,
    /// Something happened to a session.
    Event {
        /// The session's folder.
        folder: PathBuf,
        session_id: String,
        /// Unix milliseconds.
        at: i64,
        event: SessionEventBody,
    },
}

/// What happened (`EventMessage::Event.event`).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum SessionEventBody {
    Created {
        session: Box<Session>,
    },
    /// Any change to the session (name, status, cwd, title, controller, …).
    Updated {
        session: Box<Session>,
    },
    Removed,
    Exited {
        #[serde(default)]
        code: Option<i32>,
    },
    Lifecycle {
        lifecycle: Lifecycle,
    },
    /// Written by the session's own program: untrusted.
    Reported {
        reported: Reported,
    },
    /// New output (at most one a second per session).
    Activity,
}

impl EventMessage {
    /// The message for a daemon event; `None` for kinds this API doesn't
    /// know (a newer daemon's).
    pub fn from_envelope(envelope: EventEnvelope) -> Option<Self> {
        let event = match envelope.event {
            SessionEvent::Created { session } => SessionEventBody::Created {
                session: Box::new(session.into()),
            },
            SessionEvent::Updated { session } => SessionEventBody::Updated {
                session: Box::new(session.into()),
            },
            SessionEvent::Removed => SessionEventBody::Removed,
            SessionEvent::Exited { code } => SessionEventBody::Exited { code },
            SessionEvent::Lifecycle { lifecycle } => SessionEventBody::Lifecycle { lifecycle },
            SessionEvent::Reported { reported } => SessionEventBody::Reported {
                reported: reported.into(),
            },
            SessionEvent::Activity => SessionEventBody::Activity,
            // Reply text is never offered over HTTP; the API doesn't ask for it.
            SessionEvent::Reply { .. } | SessionEvent::Unknown => return None,
        };
        Some(EventMessage::Event {
            folder: envelope.scope.path().to_path_buf(),
            session_id: envelope.session_id.as_str().to_owned(),
            at: envelope.at,
            event,
        })
    }
}

/// Server → client text messages on `GET /v1/sessions/{id}/attach`
/// (WebSocket). Terminal output travels as binary frames.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum AttachMessage {
    /// Sent once, first. Feeding `checkpoint` (base64) to a fresh terminal of
    /// `cols`×`rows` shows the current screen; output continues from
    /// `offset`.
    Attached {
        session: Box<Session>,
        role: Role,
        cols: u16,
        rows: u16,
        checkpoint: String,
        offset: u64,
    },
    /// The terminal was resized: reset the terminal to `checkpoint` at this
    /// size.
    Resized {
        cols: u16,
        rows: u16,
        checkpoint: String,
        offset: u64,
    },
    /// This client became controller or observer.
    RoleChanged {
        role: Role,
    },
    Title {
        title: String,
    },
    Bell,
    /// The program exited; the server closes the socket next.
    Exited {
        #[serde(default)]
        code: Option<i32>,
    },
    /// Output was dropped because this client fell behind: attach again.
    Lagged,
}

impl AttachMessage {
    /// The first message of an attach stream.
    pub fn attached(attached: Attached) -> Self {
        AttachMessage::Attached {
            session: Box::new(attached.session.into()),
            role: attached.role,
            cols: attached.cols,
            rows: attached.rows,
            checkpoint: attached.checkpoint,
            offset: attached.offset,
        }
    }

    /// The message for a daemon stream event; `None` for events the API
    /// doesn't forward (`cwd`, `clipboard`; the session's `updated` event
    /// carries the cwd).
    pub fn from_event(event: StreamEvent) -> Option<Self> {
        Some(match event {
            StreamEvent::Resized {
                cols,
                rows,
                checkpoint,
                offset,
            } => AttachMessage::Resized {
                cols,
                rows,
                checkpoint,
                offset,
            },
            StreamEvent::RoleChanged { role } => AttachMessage::RoleChanged { role },
            StreamEvent::Title { title } => AttachMessage::Title { title },
            StreamEvent::Bell => AttachMessage::Bell,
            StreamEvent::Exited { code } => AttachMessage::Exited { code },
            StreamEvent::Lagged { .. } => AttachMessage::Lagged,
            StreamEvent::Cwd { .. } | StreamEvent::Clipboard { .. } => return None,
        })
    }
}

/// Client → server text messages on an attach stream. Input bytes travel as
/// binary frames (a controller's only; an observer's are ignored).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum AttachCommand {
    /// Controller: resize the terminal.
    Resize { cols: u16, rows: u16 },
    /// Become controller at this size.
    Promote { cols: u16, rows: u16 },
    /// Become observer.
    Demote,
    /// Observer: take this size unless the controller is typing.
    Fit { cols: u16, rows: u16 },
}

impl From<AttachCommand> for StreamCommand {
    fn from(command: AttachCommand) -> Self {
        match command {
            AttachCommand::Resize { cols, rows } => StreamCommand::Resize { cols, rows },
            AttachCommand::Promote { cols, rows } => StreamCommand::Promote { cols, rows },
            AttachCommand::Demote => StreamCommand::Demote,
            AttachCommand::Fit { cols, rows } => StreamCommand::Fit { cols, rows },
        }
    }
}

