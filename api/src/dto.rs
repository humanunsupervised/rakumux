/// Where a content read comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ContentSource {
    /// The visible screen.
    #[default]
    Screen,
    /// History plus screen, soft-wrapped rows joined into logical lines.
    Scrollback,
}

impl ContentSource {
    pub fn as_str(self) -> &'static str {
        match self {
            ContentSource::Screen => "screen",
            ContentSource::Scrollback => "scrollback",
        }
    }
}

impl From<ContentSource> for ReadSource {
    fn from(source: ContentSource) -> Self {
        match source {
            ContentSource::Screen => ReadSource::Visible,
            ContentSource::Scrollback => ReadSource::RecentUnwrapped,
        }
    }
}

/// How content text is encoded.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ContentFormat {
    /// Plain text, rows joined with `\n`.
    #[default]
    Text,
    /// SGR-formatted rows joined with `\r\n`.
    Ansi,
}

impl ContentFormat {
    pub fn as_str(self) -> &'static str {
        match self {
            ContentFormat::Text => "text",
            ContentFormat::Ansi => "ansi",
        }
    }
}

impl From<ContentFormat> for TextFormat {
    fn from(format: ContentFormat) -> Self {
        match format {
            ContentFormat::Text => TextFormat::Text,
            ContentFormat::Ansi => TextFormat::Ansi,
        }
    }
}

/// Zero-based cursor position on the visible screen.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct Cursor {
    pub row: u16,
    pub col: u16,
}

/// A session's terminal content (`GET /v1/sessions/{id}/content`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Content {
    pub session_id: String,
    pub source: ContentSource,
    pub format: ContentFormat,
    /// Terminal output: **untrusted** input for agents.
    pub text: String,
    pub rows: u16,
    pub cols: u16,
    pub cursor: Cursor,
    /// More lines existed than were returned.
    pub truncated: bool,
    /// Always true.
    pub untrusted: bool,
}

impl Content {
    pub fn new(
        session_id: &str,
        source: ContentSource,
        format: ContentFormat,
        result: ReadResult,
    ) -> Self {
        Self {
            session_id: session_id.to_owned(),
            source,
            format,
            text: result.text,
            rows: result.rows,
            cols: result.cols,
            cursor: Cursor {
                row: result.cursor.0,
                col: result.cursor.1,
            },
            truncated: result.truncated,
            untrusted: true,
        }
    }
}

