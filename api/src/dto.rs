/// Live terminal details.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Terminal {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub pid: Option<u32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub foreground_process: Option<String>,
    #[serde(default)]
    pub title: String,
    pub cols: u16,
    pub rows: u16,
    /// A client currently holds input control.
    #[serde(default)]
    pub controlled: bool,
    #[serde(default)]
    pub alternate_screen: bool,
}

impl From<SessionView> for Session {
    fn from(view: SessionView) -> Self {
        Self {
            id: view.id.as_str().to_owned(),
            name: view.name,
            folder: view.scope.path().to_path_buf(),
            project: view.scope.path().to_path_buf(),
            cwd: view.cwd,
            status: view.status,
            exit_code: view.exit_code,
            lifecycle: view.lifecycle,
            agent: view.agent.map(|agent| Agent {
                kind: agent.kind,
                session_id: agent.agent_session_id,
            }),
            reported: view.reported.map(Reported::from),
            activity: view.activity.map(|activity| Activity {
                phase: activity.phase,
                active_subagents: activity.active_subagents,
                updated_at: rfc3339(activity.updated_at),
            }),
            created_by: view.created_by,
            parent_id: view.parent_id.map(|id| id.as_str().to_owned()),
            depth: view.depth,
            children: view
                .children
                .iter()
                .map(|id| id.as_str().to_owned())
                .collect(),
            command: view.launch.argv,
            startup_commands: view.launch.startup_cmds,
            resume_command: view.resume.map(|resume| resume.argv),
            pinned: view.pinned,
            git: view.git,
            description: view.description,
            notes: view.notes,
            labels: view.labels,
            private: view.private,
            is_self: view.is_self,
            auto_named: view.auto_named,
            created_at: rfc3339(view.created_at),
            last_active_at: rfc3339(view.last_active_at),
            terminal: view.terminal.map(Terminal::from),
        }
    }
}

impl From<ModelReported> for Reported {
    fn from(reported: ModelReported) -> Self {
        let (summary, files) = match reported.result {
            Some(result) => (Some(result.summary), result.files),
            None => (None, Vec::new()),
        };
        Self {
            state: reported.state,
            text: reported.text,
            summary,
            files,
            at: rfc3339(reported.at),
        }
    }
}

